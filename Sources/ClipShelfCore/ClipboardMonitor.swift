import AppKit

/// Polls the pasteboard (macOS has no change notification) and reports new text.
public final class ClipboardMonitor {
    /// Types that password managers and others use to mark content that shouldn't be recorded.
    /// See http://nspasteboard.org
    public static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType"),
        .init("com.typeit4me.clipping"),
        .init("Pasteboard generator type"),
        .init("net.antelle.keeweb"),
    ]

    private let pasteboard: NSPasteboard
    private let defaults: UserDefaults
    private let onText: (String) -> Void
    private var lastChangeCount: Int?
    private var timer: Timer?

    public init(pasteboard: NSPasteboard = .general, defaults: UserDefaults = .standard,
                onText: @escaping (String) -> Void) {
        self.pasteboard = pasteboard
        self.defaults = defaults
        self.onText = onText
    }

    public var isPaused: Bool {
        get { defaults.bool(forKey: "paused") }
        set { defaults.set(newValue, forKey: "paused") }
    }

    /// Records what's on the clipboard now, then keeps polling for changes.
    public func start() {
        poll()
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common) // keep recording while menus are open
        self.timer = timer
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Checks the pasteboard once. Returns true if new text was reported.
    @discardableResult
    func poll() -> Bool {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return false }
        lastChangeCount = count
        guard !isPaused,
              let types = pasteboard.types,
              Set(types).isDisjoint(with: Self.ignoredTypes),
              let text = pasteboard.string(forType: .string) else { return false }
        onText(text)
        return true
    }
}
